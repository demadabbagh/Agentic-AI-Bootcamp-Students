// Demo entries for My Trips, loaded only when the user presses "Load Sample Trips".
// Every entry carries sample: true and a label saying exactly what it is.

function to24h(label) {
  const m = /^(\d{1,2}):(\d{2})\s*(AM|PM)$/i.exec(label || '')
  if (!m) return null
  let hour = Number(m[1]) % 12
  if (m[3].toUpperCase() === 'PM') hour += 12
  return `${String(hour).padStart(2, '0')}:${m[2]}`
}

function addMinutes(hhmm, minutes) {
  const [h, m] = hhmm.split(':').map(Number)
  const total = h * 60 + m + minutes
  return `${String(Math.floor(total / 60)).padStart(2, '0')}:${String(total % 60).padStart(2, '0')}`
}

function durationMinutes(label) {
  const hours = /([\d.]+)\s*hour/.exec(label || '')
  if (hours) return Math.round(Number(hours[1]) * 60)
  const minutes = /(\d+)\s*min/.exec(label || '')
  return minutes ? Number(minutes[1]) : null
}

function priceValue(label) {
  if (label === 'Free') return 0
  const m = /^\$(\d+(?:\.\d+)?)$/.exec(label || '')
  return m ? Number(m[1]) : null
}

// The dashboard's hand-written Istanbul preview, in the backend itinerary shape.
function istanbulSampleResult() {
  const start = new Date(`${SAMPLE_TRIP.startDate}T12:00:00Z`)
  return {
    session_id: 'sample-istanbul-handwritten',
    status: 'verification_required',
    pending_action: null,
    message: 'Sample trip: hand-written demo data. It was not generated by AI and was not verified.',
    itinerary: {
      destination: SAMPLE_TRIP.destination,
      currency: SAMPLE_TRIP.currency,
      travellers: SAMPLE_TRIP.travellers,
      budget_total: SAMPLE_TRIP.budgetTotal,
      estimated_total: SAMPLE_TRIP.estimatedTotal,
      days: SAMPLE_TRIP.days.map((day, index) => {
        const date = new Date(start.getTime() + index * 86400000).toISOString().slice(0, 10)
        return {
          date,
          activities: day.activities.map((a) => {
            const startTime = to24h(a.time)
            const minutes = durationMinutes(a.duration)
            return {
              name: a.name,
              start_time: startTime,
              end_time: startTime && minutes ? addMinutes(startTime, minutes) : null,
              estimated_cost: priceValue(a.price),
              notes: a.type,
            }
          }),
        }
      }),
    },
  }
}

